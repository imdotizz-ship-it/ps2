"""gen_font.py PNG MET OUT.h : pack the game's own HUD font (HelveticaNeue LT 65 Medium) into a
256x256 4-bit coverage atlas + glyph table for ui.c (Latin-1 subset used by the mod texts)."""
import sys
from PIL import Image
png, met, out = sys.argv[1:4]
im = Image.open(png).convert('RGBA')
lines = open(met, 'rb').read().decode('latin-1').split('\r\n')
G = {}
for l in lines[3:]:
    p = l.split()
    if len(p) >= 5 and p[0].isdigit():
        c, x0, y0, x1, y1 = map(int, p[:5]); G[c] = (x0, y0, x1, y1)
want = list(range(32, 127)) + [ord(c) for c in 'ÁÀÂÃÉÊÍÓÔÕÚÜÇáàâãéêíóôõúüç°ºª·']
W = H = 256
atlas = Image.new('L', (W, H), 0)
x = y = 0; rowh = 0; tab = []
for c in want:
    if c not in G: continue
    x0, y0, x1, y1 = G[c]; w, h = x1 - x0, y1 - y0
    if x + w + 1 > W: x = 0; y += rowh + 1; rowh = 0
    g = im.crop((x0, y0, x1, y1)).split()[3]
    atlas.paste(g, (x, y))
    tab.append((c, x, y, w, h)); x += w + 1; rowh = max(rowh, h)
assert y + rowh <= H, 'atlas full'
px = atlas.load()
nib = bytearray()
for yy in range(H):
    for xx in range(0, W, 2):
        a, b = px[xx, yy] >> 4, px[xx + 1, yy] >> 4
        nib.append(a | (b << 4))
with open(out, 'w') as f:
    f.write('/* generated by gen_font.py from MENU\\FONT\\%s */\n' % png.split('/')[-1])
    f.write('#define FONT_W %d\n#define FONT_H %d\n#define FONT_LINE %d\n#define FONT_N %d\n' % (W, H, max(t[4] for t in tab), len(tab)))
    f.write('static const unsigned short FONT_GLYPH[FONT_N][5] = {\n')
    f.write(',\n'.join('{%d,%d,%d,%d,%d}' % t for t in tab) + '};\n')
    f.write('static const unsigned char FONT_A4[%d] = {\n' % len(nib))
    for i in range(0, len(nib), 32): f.write(','.join(str(v) for v in nib[i:i + 32]) + ',\n')
    f.write('};\n')
print(len(tab), 'glyphs, used rows to', y + rowh)
