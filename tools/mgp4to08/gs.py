def addr32(x,y,bw):  # word address
    page=(y//32)*bw+x//64
    blk=BT32[(y%32)//8][(x%64)//8]
    col=(y%8)//2
    return page*2048+blk*64+col*16+CT32[y%2][x%8]
def addr4(x,y,bw):   # nibble address, bw in 64px units
    page=(y//128)*(bw//2)+x//128
    blk=BT4[(y%128)//16][(x%128)//32]
    return page*16384+blk*512+CT4[y%16][x%32]
def addr8(x,y,bw):   # byte address
    page=(y//64)*(bw//2)+x//128
    blk=BT8[(y%64)//16][(x%128)//16]
    return page*8192+blk*256+CT8[y%16][x%16]

def ct32_write(words,tw,th,bw,mem=None):
    if mem is None: mem=np.zeros(1<<20,np.uint32)
    for y in range(th):
        for x in range(tw):
            mem[addr32(x,y,bw)]=words[y*tw+x]
    return mem
def read4(mem,w,h,bw):
    b=mem.view(np.uint8); out=np.zeros((h,w),np.uint8)
    for y in range(h):
        for x in range(w):
            a=addr4(x,y,bw); out[y,x]=(b[a>>1]>>((a&1)*4))&15
    return out
def read8(mem,w,h,bw):
    b=mem.view(np.uint8); out=np.zeros((h,w),np.uint8)
    for y in range(h):
        for x in range(w): out[y,x]=b[addr8(x,y,bw)]
    return out
def write4(img,bw,mem=None):
    if mem is None: mem=np.zeros(1<<20,np.uint32)
    b=mem.view(np.uint8); h,w=img.shape
    for y in range(h):
        for x in range(w):
            a=addr4(x,y,bw); s=(a&1)*4
            b[a>>1]=(b[a>>1]&(0xF0>>s))|((int(img[y,x])&15)<<s)
    return mem
def ct32_read(mem,tw,th,bw):
    return np.array([mem[addr32(x,y,bw)] for y in range(th) for x in range(tw)],np.uint32)
